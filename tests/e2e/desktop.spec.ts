import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { basename, join, resolve, sep } from 'node:path'

test('desktop CRUD, details, backups, and restart persistence', async () => {
  const userData = await mkdtemp(join(tmpdir(), 'xuding-test-'))
  const { ELECTRON_RUN_AS_NODE: _, ...env } = process.env
  const launch = () => electron.launch({ args: ['.'], env: { ...env, XUDING_DATA_DIR: userData } })
  let app = await launch()
  try {
    let page = await app.firstWindow()
    const errors: string[] = []
    page.on('pageerror', (e) => errors.push(e.message))
    await expect(page.getByRole('heading', { name: '每一笔订阅，心里有数。' })).toBeVisible()
    await expect(page.getByRole('button', { name: '新增订阅', exact: true })).toHaveCount(0)
    await expect(page.getByText('SUBSCRIPTIONS, SIMPLIFIED')).toHaveCount(0)
    const currencyPicker = page.getByRole('combobox', { name: '统计币种' })
    await currencyPicker.focus()
    await page.keyboard.press('ArrowDown')
    await expect(page.getByRole('listbox')).toBeVisible()
    await expect(page.locator('.select-chevron')).toHaveClass(/is-open/)
    await page.keyboard.press('Escape')
    await expect(page.getByRole('listbox')).toBeHidden()
    await expect(page.locator('.select-chevron')).not.toHaveClass(/is-open/)
    const sidebarWidth = () =>
      page.locator('.sidebar').evaluate((node) => node.getBoundingClientRect().width)
    await page.getByRole('button', { name: '收起侧栏', exact: true }).click()
    await expect.poll(sidebarWidth).toBeLessThan(75)
    await page.reload()
    await expect(page.getByRole('button', { name: '展开侧栏', exact: true })).toBeVisible()
    await page
      .getByRole('navigation')
      .getByRole('button', { name: '扣款日历', exact: true })
      .click()
    await expect(page.getByRole('heading', { name: '扣款日历', exact: true })).toBeVisible()
    await page.keyboard.press('Control+b')
    await expect.poll(sidebarWidth).toBeGreaterThan(170)
    await page.getByRole('navigation').getByRole('button', { name: '总览', exact: true }).click()
    expect(
      await page.evaluate(() => typeof (window as unknown as { require?: unknown }).require)
    ).toBe('undefined')
    await page
      .getByRole('navigation')
      .getByRole('button', { name: /我的订阅/ })
      .click()
    await page.getByRole('button', { name: '新增订阅', exact: true }).click()
    await page.getByRole('textbox', { name: '订阅名称' }).fill('桌面测试会员')
    await page.keyboard.press('Control+b')
    await expect(page.getByRole('button', { name: '收起侧栏', exact: true })).toBeVisible()
    await page.getByRole('spinbutton', { name: '金额', exact: true }).fill('19.99')
    await page.getByRole('combobox', { name: '币种', exact: true }).click()
    await page.getByRole('option', { name: '美元 USD', exact: true }).click()
    await page.getByRole('combobox', { name: '周期单位', exact: true }).click()
    await page.getByRole('option', { name: '年', exact: true }).click()
    await page.getByRole('combobox', { name: '分类', exact: true }).click()
    await page.getByRole('option', { name: '学习成长', exact: true }).click()
    await page.getByRole('combobox', { name: '提醒时间', exact: true }).click()
    await page.getByRole('option', { name: '提前 7 天', exact: true }).click()
    await page.getByRole('switch', { name: '自动续费已开启' }).click()
    await expect(page.locator('input[type="number"], input[type="date"], select')).toHaveCount(0)
    const anchorDate = page.getByRole('textbox', { name: '计费基准日 / 首次扣款日' })
    await anchorDate.fill('2026-02-30')
    await page.getByRole('button', { name: '添加订阅', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('请输入有效日期')
    await anchorDate.fill('2028-02-01')
    await anchorDate.press('Enter')
    await anchorDate.click()
    await page.locator('.ant-picker-dropdown').getByTitle('2028-02-29', { exact: true }).click()
    await expect(anchorDate).toHaveValue('2028-02-29')
    const amount = page.getByRole('spinbutton', { name: '金额', exact: true })
    await amount.fill('19.999')
    await page.getByRole('button', { name: '添加订阅', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('最多两位小数')
    await amount.fill('19.99')
    const interval = page.getByRole('spinbutton', { name: '每隔多少个周期' })
    await interval.focus()
    await interval.press('ArrowUp')
    await expect(interval).toHaveValue('2')
    await page.getByRole('button', { name: '添加订阅', exact: true }).click()
    await expect(page.getByRole('heading', { name: '桌面测试会员', exact: true })).toBeVisible()
    await expect(page.locator('.detail-price')).toContainText('19.99')
    await expect(page.locator('input')).toHaveCount(0)
    const saved = await page.evaluate(() => window.desktop.load())
    expect(saved.ok && saved.data.subscriptions[0]).toMatchObject({
      cycle: 'year',
      currency: 'USD',
      category: '学习成长',
      reminderDays: 7,
      autoRenew: false,
      anchorDate: '2028-02-29',
      interval: 2
    })
    await page.getByRole('button', { name: '编辑订阅', exact: true }).click()
    await page.getByRole('spinbutton', { name: '金额', exact: true }).fill('29.99')
    await page.getByRole('button', { name: '取消编辑', exact: true }).click()
    await expect(page.locator('.detail-price')).toContainText('19.99')
    await page.getByRole('button', { name: '编辑订阅', exact: true }).click()
    await page.getByRole('spinbutton', { name: '金额', exact: true }).fill('29.99')
    await page.getByRole('button', { name: '保存修改', exact: true }).click()
    await expect(page.locator('.detail-price')).toContainText('29.99')
    await page.getByRole('button', { name: '返回我的订阅', exact: true }).click()
    await page.getByRole('combobox', { name: '分类筛选', exact: true }).click()
    await page.getByRole('option', { name: '影音娱乐', exact: true }).click()
    await expect(
      page.getByRole('button', { name: '查看 桌面测试会员 详情', exact: true })
    ).toHaveCount(0)
    await page.getByRole('combobox', { name: '分类筛选', exact: true }).click()
    await page.getByRole('option', { name: '学习成长', exact: true }).click()
    await page.getByRole('button', { name: '查看 桌面测试会员 详情', exact: true }).click()
    await expect(page.getByRole('heading', { name: '费用与周期' })).toBeVisible()
    const exported = join(userData, 'backup.json')
    await app.evaluate(({ dialog }, file) => {
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: file })
    }, exported)
    await page.getByRole('button', { name: '设置与备份', exact: true }).click()
    const reminderHelp = page.getByRole('button', { name: '桌面提醒说明' })
    await reminderHelp.hover()
    await expect(page.getByRole('tooltip')).toContainText('关闭应用或电脑休眠期间不会发送通知')
    await page.getByRole('heading', { name: '设置与备份' }).hover()
    await expect(page.getByRole('tooltip')).toBeHidden()
    await page.getByRole('button', { name: '数据备份说明' }).focus()
    await expect(page.getByRole('tooltip')).toContainText('本地数据库与备份均未加密')
    await page.getByRole('switch', { name: '开启桌面通知' }).focus()
    await expect(page.getByRole('tooltip')).toBeHidden()
    await page.getByRole('switch', { name: '开启桌面通知' }).click()
    await expect(page.getByRole('switch', { name: '开启桌面通知' })).toBeChecked()
    await page.getByRole('switch', { name: '开启桌面通知' }).click()
    await expect(page.getByRole('switch', { name: '开启桌面通知' })).not.toBeChecked()
    await page.getByRole('button', { name: '导出备份', exact: true }).click()
    await expect(page.getByRole('status')).toHaveText('备份已导出。')
    expect(JSON.parse(await readFile(exported, 'utf8')).subscriptions[0].amountMinor).toBe(2999)
    await app.evaluate(({ dialog }, file) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] })
      dialog.showMessageBox = async () => ({ response: 1, checkboxChecked: false })
    }, exported)
    await page.getByRole('button', { name: '导入备份', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('已导入 1 项订阅')
    await page.getByRole('button', { name: '收起侧栏', exact: true }).click()
    await app.close()
    app = await launch()
    page = await app.firstWindow()
    await expect(page.getByRole('button', { name: '展开侧栏', exact: true })).toBeVisible()
    await page
      .getByRole('navigation')
      .getByRole('button', { name: /我的订阅/ })
      .click()
    await page.getByRole('button', { name: '查看 桌面测试会员 详情', exact: true }).click()
    await expect(page.locator('.detail-price')).toContainText('29.99')
    await page.getByRole('button', { name: '归档订阅', exact: true }).click()
    await page.getByRole('button', { name: '确认归档', exact: true }).click()
    await expect(page.locator('.badge')).toHaveText('已归档')
    expect(errors).toEqual([])
  } finally {
    await app.close()
    const target = resolve(userData)
    if (!target.startsWith(resolve(tmpdir()) + sep) || !basename(target).startsWith('xuding-test-'))
      throw new Error('Refusing to remove unexpected test directory')
    await rm(target, { recursive: true, force: true })
  }
})
